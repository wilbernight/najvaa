// Builds public/voicefx-worklet.js from the two DSP engines (each kept in its
// own scope) plus the AudioWorkletProcessor wrapper. Run: node deploy/build-voicefx.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = fs.existsSync(path.join(here, 'voicefx')) ? path.join(here, 'voicefx') : here; // repo: deploy/voicefx, package: alongside
const out = path.join(here, '..', 'public', 'voicefx-worklet.js');

const scoped = (file, name) => {
  const code = fs.readFileSync(path.join(src, file), 'utf8')
    .replace(/^export default VoiceFx;\s*$/m, '')
    .replace(/^export class VoiceFx/m, 'class VoiceFx')
    .replace(/^export /gm, '');
  if (/^\s*import /m.test(code)) throw new Error(`${file}: imports are not allowed in a worklet`);
  return `const ${name} = (() => {\n${code}\nreturn VoiceFx;\n})();\n`;
};

const header = `// Najva female-voice filter (AudioWorklet). Generated by deploy/build-voicefx.mjs
// from deploy/voicefx/*.mjs - edit those, not this file.
//
// Runs entirely on the device, before encryption: the microphone goes in, a
// voice with a woman's pitch and vocal-tract resonances comes out.
// Two engines:
//  - psola (default): time-domain pitch-synchronous overlap-add with formant
//    shifting by resampling. Light on CPU, ~26 ms latency.
//  - vocoder: STFT phase vocoder with spectral-envelope separation and
//    shape-invariant phase. Slightly closer to a female reference, heavier.
//  - robot: LPC vocoder with a fixed neutral pitch: an anonymous robotic
//    voice with no gender and none of the speaker's own character.
// "auto" tracks the speaker's running median F0 and moves it to ~200 Hz
// (ratio clamped 1.3..2.0); formants move up ~17%.
`;

const wrapper = `
const ENGINES = { psola: PsolaFx, vocoder: VocoderFx, robot: RobotFx };
export const PRESETS = {
  natural: { engine: 'psola', auto: true, formant: 1.17, mix: 1 },
  soft: { engine: 'psola', auto: true, formant: 1.12, mix: 1 },
  bright: { engine: 'vocoder', auto: true, formant: 1.2, mix: 1 },
};

if (typeof registerProcessor === 'function') {
  class NajvaVoiceFx extends AudioWorkletProcessor {
    constructor(options) {
      super();
      const p = { ...PRESETS.natural, ...(options && options.processorOptions) };
      const Engine = ENGINES[p.engine] || PsolaFx;
      this.fx = new Engine(sampleRate, p);
      this.fx.setParams(p);
      this.silence = new Float32Array(128);
      this.port.onmessage = (e) => {
        const d = e.data;
        if (d && d.type === 'params') this.fx.setParams(d);
      };
    }

    process(inputs, outputs) {
      const out = outputs[0];
      if (!out || !out.length) return true;
      const ch0 = out[0];
      const n = ch0.length;
      let src = inputs[0] && inputs[0][0];
      if (!src || src.length !== n) {
        if (this.silence.length !== n) this.silence = new Float32Array(n);
        else this.silence.fill(0);
        if (src) this.silence.set(src.subarray(0, n));
        src = this.silence;
      }
      this.fx.process(src, ch0);
      for (let c = 1; c < out.length; c++) out[c].set(ch0);
      return true;
    }
  }
  registerProcessor('najva-voicefx', NajvaVoiceFx);

  // Voice-message capture: passes the (mono) input to the page in blocks, so
  // the page can store plain PCM (a WAV plays on every browser, unlike the
  // formats MediaRecorder produces, which differ per platform).
  class NajvaCapture extends AudioWorkletProcessor {
    constructor() {
      super();
      this.buf = new Float32Array(4096);
      this.n = 0;
      this.on = true;
      this.port.onmessage = (e) => {
        if (e.data !== 'stop' || !this.on) return;
        this.on = false;
        if (this.n) this.port.postMessage(this.buf.slice(0, this.n));
        this.port.postMessage({ done: true });
      };
    }

    process(inputs, outputs) {
      if (!this.on) return false;
      const ch = inputs[0] && inputs[0][0];
      if (ch) {
        for (let i = 0; i < ch.length; i++) {
          this.buf[this.n++] = ch[i];
          if (this.n === this.buf.length) {
            this.port.postMessage(this.buf, [this.buf.buffer]);
            this.buf = new Float32Array(4096);
            this.n = 0;
          }
        }
      }
      const out = outputs[0] && outputs[0][0];
      if (out) out.fill(0);
      return true;
    }
  }
  registerProcessor('najva-capture', NajvaCapture);
}

export { PsolaFx, VocoderFx, RobotFx };
export const VoiceFx = PsolaFx;
export default PsolaFx;
`;

fs.writeFileSync(out, header + '\n' + scoped('psola.mjs', 'PsolaFx') + '\n' + scoped('vocoder.mjs', 'VocoderFx') + '\n' + scoped('robot.mjs', 'RobotFx') + wrapper);
console.log('wrote', out, fs.statSync(out).size, 'bytes');
